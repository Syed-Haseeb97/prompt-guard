const GITIGNORE_SNIPPET = `
# prompt-guard
.prompt-guard/runs/
.prompt-guard/cache/
`;

/** Scaffold a prompt-guard project. */
export async function runInit(options: InitOptions): Promise<InitResult> {
  const styler = createOutputStyler(options.context);
  const targetDir = path.resolve(options.cwd, options.targetDir ?? '.');
  const created: string[] = [];
  const skipped: string[] = [];

  await ensureDir(targetDir);

  const configPath = path.join(targetDir, DEFAULT_CONFIG_FILE);
  if (await pathExists(configPath)) {
    if (!options.force) {
      skipped.push(configPath);
    } else {
      await saveConfig(configPath, defaultConfig());
      created.push(configPath);
    }
  } else {
    await saveConfig(configPath, defaultConfig());
    created.push(configPath);
  }

  const suitesDir = path.join(targetDir, 'suites');
  await ensureDir(suitesDir);

  if (!options.noSamples) {
    const samplePath = path.join(suitesDir, 'smoke.suite.json');
    if ((await pathExists(samplePath)) && !options.force) {
      skipped.push(samplePath);
    } else {
      await writeJsonFile(samplePath, SAMPLE_SUITE);
      created.push(samplePath);
    }
  }

  const benchmarksDir = path.join(targetDir, 'benchmarks');
  await ensureDir(benchmarksDir);
  const benchmarkPath = path.join(benchmarksDir, 'baseline.benchmark.json');
  if ((await pathExists(benchmarkPath)) && !options.force) {
    skipped.push(benchmarkPath);
  } else {
    await writeJsonFile(benchmarkPath, SAMPLE_BENCHMARK);
    created.push(benchmarkPath);
  }

  const gitignorePath = path.join(targetDir, '.gitignore');
  const existingIgnore = (await pathExists(gitignorePath))
    ? await import('node:fs/promises').then((fs) => fs.readFile(gitignorePath, 'utf8'))
    : '';
  if (!existingIgnore.includes('.prompt-guard/runs/')) {
    const separator = existingIgnore.length > 0 && !existingIgnore.endsWith('\n') ? '\n' : '';
    await writeTextFile(gitignorePath, `${existingIgnore}${separator}${GITIGNORE_SNIPPET}`);
    created.push(gitignorePath);
  } else {
    skipped.push(gitignorePath);
  }

  if (!options.context.quiet) {
    const lines: string[] = [];
    lines.push(styler.boldGreen('✔ prompt-guard project initialised'));
    lines.push('');
    for (const file of created) {
      lines.push(`  ${styler.green('created')}  ${path.relative(targetDir, file) || file}`);
    }
    for (const file of skipped) {
      lines.push(`  ${styler.yellow('skipped')}  ${path.relative(targetDir, file) || file} (already exists)`);
    }
    lines.push('');
    lines.push(styler.bold('Next steps'));
    lines.push(`  1. ${styler.cyan('prompt-guard run')}                       run the generated smoke suite`);
    lines.push(`  2. ${styler.cyan('prompt-guard run --provider openai --model gpt-4o-mini')}`);
    lines.push(`  3. ${styler.cyan('prompt-guard compare <runA> <runB>')}      diff two runs`);
    process.stdout.write(`${lines.join('\n')}\n`);
  }

  if (created.length === 0 && skipped.length > 0) {
    throw new CliError('nothing to do — the project already exists (use --force to overwrite)', 1);
  }

  return { created, skipped, configPath };
}
