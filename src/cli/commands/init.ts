export interface InitOptions {
  cwd: string;
  /** Directory to scaffold into. */
  targetDir?: string;
  /** Overwrite existing files. */
  force?: boolean;
  /** Skip creating the sample suite. */
  noSamples?: boolean;
  context: OutputContext;
}

export interface InitResult {
  created: string[];
  skipped: string[];
  configPath: string;
}

